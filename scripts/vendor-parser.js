// Bundle the pinned parser locally: no runtime downloads or page-global parser.
const fs = require("node:fs");
const path = require("node:path");
const target = path.join(__dirname, "../src/vendor");
const packageRoot = path.dirname(require.resolve("acorn/package.json"));
const source = fs.readFileSync(path.join(packageRoot, "dist/acorn.js"), "utf8");
fs.mkdirSync(target, { recursive: true });
fs.writeFileSync(path.join(target, "acorn.js"), `// Generated by scripts/vendor-parser.js. See acorn.LICENSE.
(function(root, factory) {
  const parser = factory();
  if (typeof module === "object" && module.exports) module.exports = parser;
  if (root) root.__SA_BOT_MAIN_V1__.parseJavaScript = parser.parse;
})(typeof window === "object" ? window : null, function() {
  const exports = {};
  const module = {exports};
  const define = undefined;
${source}
  return module.exports;
});
`);
fs.copyFileSync(path.join(packageRoot, "LICENSE"), path.join(target, "acorn.LICENSE"));
